/**
 * Builds the site concierge's knowledge (S7) from dist/llms-full.txt, which is generated from the content
 * collections, so the concierge always knows exactly what the site says. Runs at the end of `npm run build` and writes
 * api/_demo/data/site-kb.js (committed too, so the function never depends on build order). Chunks: the intro facts
 * line by line, then each agent/service/product/case study with its summary, and its Q&As in pairs.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const src = readFileSync(new URL('../dist/llms-full.txt', import.meta.url), 'utf8');
const siteTs = readFileSync(new URL('../src/data/site.ts', import.meta.url), 'utf8');
const bookingUrl = siteTs.match(/bookingUrl:\s*'([^']+)'/)?.[1] ?? 'https://visionbotix.com/contact/';

const chunks = [];
const push = (title, url, text) => {
  text = text.replace(/\s+/g, ' ').trim();
  if (text.length > 20) chunks.push({ id: `k${chunks.length + 1}`, title: title.slice(0, 90), url, text: text.slice(0, 1400) });
};

const [intro, ...sections] = src.split(/\n(?=## )/);
for (const line of intro.split('\n')) {
  const m = line.match(/^([A-Z][^:]{2,120}):\s(.+)/);
  if (m) {
    const label = m[1].replace(/\s*\(.*$/, ''); // "Pricing (USD, "from")" → "Pricing"
    push(`Visionbotix: ${label}`, label.startsWith('Typical') ? 'https://visionbotix.com/estimate/' : label === 'Pricing' ? 'https://visionbotix.com/pricing/' : 'https://visionbotix.com/about/', `${m[1]}: ${m[2]}`);
  }
  else if (line.startsWith('>')) push('About Visionbotix', 'https://visionbotix.com/about/', line.slice(1));
}

for (const sec of sections) {
  const [head, ...lines] = sec.split('\n');
  const section = head.replace(/^##\s*/, '').trim();
  let item = null;
  let qa = [];
  const flushQa = () => {
    for (let i = 0; i < qa.length; i += 2) push(`${item.title}: questions`, item.url, qa.slice(i, i + 2).join(' '));
    qa = [];
  };
  const loose = [];
  for (const line of lines) {
    const it = line.match(/^- \[([^\]]+)\]\((https:\/\/visionbotix\.com[^)]*)\):\s*(.*)/);
    if (it) {
      if (item) flushQa();
      item = { title: it[1], url: it[2] };
      // The price ends each line in llms-full.txt; put it first so trimming a long summary never drops it.
      const price = it[3].match(/\s((?:From|from) \$[\d,]+[^.]*?)$/)?.[1];
      push(`${section}: ${it[1]}`, it[2], price ? `Price: ${price}. ${it[3].slice(0, -price.length).trim()}` : it[3]);
    } else if (item && /^- Q: /.test(line)) qa.push(line.replace(/^- /, ''));
    else if (item && /^\s+A: /.test(line)) qa[qa.length - 1] += ` ${line.trim()}`;
    else if (line.trim()) loose.push(line.trim());
  }
  if (item) flushQa();
  if (loose.length) for (let i = 0; i < loose.length; i += 6) push(section, 'https://visionbotix.com/', loose.slice(i, i + 6).join(' '));
}

mkdirSync(new URL('../api/_demo/data/', import.meta.url), { recursive: true });
writeFileSync(
  new URL('../api/_demo/data/site-kb.js', import.meta.url),
  `// Generated by scripts/demo-kb.mjs from dist/llms-full.txt. Do not edit by hand.\nexport const bookingUrl = ${JSON.stringify(bookingUrl)};\nexport default ${JSON.stringify(chunks)};\n`,
);
console.log(`demo-kb: ${chunks.length} chunks → api/_demo/data/site-kb.js`);
